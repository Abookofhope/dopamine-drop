import { chromium } from 'playwright';
import { openApp, goTab } from './harness.mjs';
const OUT = process.env.OUT;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 1 });
const page = await ctx.newPage();
await page.addInitScript(() => localStorage.setItem('dd.probe', '1'));
const pals = { biscuit: { bond: 950, pet: null, bow: '', acc: 'scarf', accs: ['scarf'], name: 'Muffin' }, mochi: { bond: 300, pet: null, bow: '' } };
await openApp(page, { reduceMotion: true, xp: 9000, runs: 40, solved: 600, onboarded: true, yarn: 3000, yarnEver: 3000, pals, palsOn: ['biscuit', 'mochi'], room: { rug: 3, window: 3, wall: 3, shelf: 1 }, glog: 'ppppsscccnnnnnnnnnnnppscnpcpcpcs', kits: [{ palsOn: ['biscuit'], perks: [], cosmetic: 'teal', station: 'hearth' }] });
const acc = k => page.evaluate(k => { const h = document.getElementById('accH_' + k); if (h && h.getAttribute('aria-expanded') !== 'true') h.click(); }, k);
await goTab(page, 'Settings'); await acc('cosmetic'); await acc('feedback'); await page.waitForTimeout(500);
await page.evaluate(() => document.getElementById('cosmeticRow').scrollIntoView({ block: 'start' })); await page.waitForTimeout(300);
await page.screenshot({ path: OUT + '/set1.png' });
await page.evaluate(() => document.getElementById('stationRow').scrollIntoView({ block: 'center' })); await page.waitForTimeout(300);
await page.screenshot({ path: OUT + '/set2.png' });
await goTab(page, 'Room'); await acc('r-seats'); await page.waitForTimeout(500);
await page.evaluate(() => document.getElementById('kitList').scrollIntoView({ block: 'center' })); await page.waitForTimeout(300);
await page.screenshot({ path: OUT + '/room.png' });
await page.evaluate(() => document.getElementById('roomScene').scrollIntoView({ block: 'start' })); await page.waitForTimeout(300);
await page.screenshot({ path: OUT + '/scene.png' });
await acc('r-cats'); await page.waitForTimeout(300);
await page.evaluate(() => { const c = [...document.querySelectorAll('.palcard')].find(c => /Muffin/.test(c.textContent)); c.click(); }); await page.waitForTimeout(600);
await page.screenshot({ path: OUT + '/pal.png' });
await page.evaluate(() => { document.querySelectorAll('.metasheet *').forEach(e => { if (e.scrollHeight > e.clientHeight + 4) e.scrollTop = 9999; }); }); await page.waitForTimeout(300);
await page.screenshot({ path: OUT + '/pal2.png' });
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
await page.evaluate(() => { const m = document.querySelector('.metasheet'); if (m) m.click(); });
await goTab(page, 'Stats'); await page.waitForTimeout(500);
await page.screenshot({ path: OUT + '/you.png' });
await b.close();
